#!/usr/bin/env python3
"""chirpers X (Common Time), track 1 "Common Time" - chirper-zero. Generator for songs/chirpers10-t1.yaml.

v1 (12 Nov): THE DRONE. Harry asked for anything at all so the groove can open to the song: the home note and the
steady pulse, with the first two cycles (five and seven sixteenths) ticking over it. The piece replaces this.
"""
import json, os

OUT = os.environ.get("C10T1_OUT", os.path.join(os.path.dirname(__file__), "../../../songs/chirpers10-t1.yaml"))
BPM = 126
BARS = 48
S = 0.25  # a sixteenth, in beats


def n(at, pitch, ln, vel, **kw):
    return {"at": round(at, 4), "pitch": pitch, "len": round(ln, 4), "vel": round(vel, 3), **kw}


def cycle(cell, period, pitches, start_bar, end_bar, vel=0.5, acc=0.2):
    """A cell of sixteenth offsets repeating every `period` sixteenths, straight through the bar lines."""
    out, k = [], 0
    t = start_bar * 4.0
    while t < end_bar * 4.0 - 1e-6:
        for j, off in enumerate(cell):
            at = t + off * S
            if at < end_bar * 4.0 - 1e-6:
                out.append(n(at, pitches[j % len(pitches)], S * 1.8, vel + (acc if j == 0 else 0)))
        t += period * S
        k += 1
    return out


def song():
    tracks = []
    # the home note: a bowed low F, re-bowed every four bars, never moving
    tracks.append({"name": "home", "patch": "contrabass-tight", "gain": "-12dB", "pan": 0.3, "sends": {"hall": "-12dB"},
                   "notes": [n(b * 4, "F1", 16.2, 0.62 + 0.04 * ((b // 4) % 2)) for b in range(0, BARS, 4)]})
    # its fifth and octave arrive, bar 9, and stay
    tracks.append({"name": "fifth", "patch": "cellos", "gain": "-15dB", "pan": 0.4, "sends": {"hall": "-8dB"},
                   "notes": [n(b * 4, p, 16.2, 0.5) for b in range(8, BARS, 4) for p in ("C2", "F2")]})
    # an open chord (no third: neither major nor minor yet)
    tracks.append({"name": "air", "patch": "juno-pad", "gain": {"value": "-17dB", "mod": [{"src": "auto.in", "amount": 1}]},
                   "pan": 0.15, "sends": {"hall": "-8dB"},
                   "auto": {"in": {"points": [["0b", -30], ["32b", -8], ["64b", 0], [f"{(BARS - 8) * 4}b", 0], [f"{BARS * 4}b", -12]]}},
                   "notes": [n(b * 4, p, 32.2, 0.5) for b in range(0, BARS, 8) for p in ("F2", "C3", "G3", "C4")]})
    # the pulse: common time, plainly, on a ride bell
    tracks.append({"name": "pulse", "patch": "obzen-kit", "gain": "-16dB",
                   "notes": [n(b, "rb", 0.5, 0.42 + (0.14 if b % 4 == 0 else 0)) for b in range(8 * 4, BARS * 4)]})
    # two cycles over it: five sixteenths on the left, seven on the right. They meet every 35 sixteenths.
    tracks.append({"name": "five", "patch": "m8-clean", "gain": "-8dB", "pan": -0.45, "sends": {"dly": "-14dB", "hall": "-12dB"},
                   "notes": cycle([0, 2, 3], 5, ["F3", "C4", "F4"], 4, BARS - 2, vel=0.42)})
    tracks.append({"name": "seven", "patch": "m8-clean", "gain": "-7dB", "pan": 0.45, "sends": {"dly": "-14dB", "hall": "-12dB"},
                   "notes": cycle([0, 2, 4, 5], 7, ["C4", "G4", "F4", "Bb4"], 16, BARS - 2, vel=0.4)})
    # the 8-string, once every sixteen bars: one open low F left to ring
    tracks.append({"name": "open", "patch": "m8-twang", "gain": "-10dB", "pan": 0,
                   "notes": [n(b * 4, "F1", 15, 0.8) for b in (16, 32)]})
    return {
        "about": "chirpers X (Common Time), track 1 by chirper-zero: v1 is a placeholder drone - the home note F, the steady pulse, and two cycles (five and seven sixteenths) ticking over it. Generated by compose/chirpers10/src/chirpers10-t1.py.",
        "tempo": BPM, "ceiling": "-1dB", "loudness": -12, "seed": 1, "tail": "3s", "length": f"{BARS * 4}b", "event_stable": True,
        "buses": {"hall": {"fx": ["reverb kind=hall decay=4.5s mix=1 predelay=30ms low_cut=150"]},
                  "dly": {"fx": ["delay time=3/16 feedback=0.35 mix=1 ping_pong=true", "reverb kind=hall decay=3s mix=0.3"]}},
        "master": {"fx": [{"type": "eq", "bands": ["hp cutoff=24", "highshelf cutoff=9000 gain=1.5dB"]}]},
        "tracks": tracks,
    }


def dump(doc):
    lines = []
    for k, v in doc.items():
        if k == "tracks":
            lines.append("tracks:")
            lines += ["  - " + json.dumps(t) for t in v]
        else:
            lines.append(f"{k}: {json.dumps(v)}")
    return "\n".join(lines) + "\n"


if __name__ == "__main__":
    open(OUT, "w").write(dump(song()))
