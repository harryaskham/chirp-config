#!/usr/bin/env python3
"""Run the master-fit stack on a song or tab2song map, one scored step at a time, keeping only steps that win.

  masterstack.py SONG.(yaml|json) REF.wav SECTIONS.txt --out DIR [--steps "eq ride ride"] [--seeds 0,11]
                 [--heldout 7,13] [--chirp BIN] [--min-gain 0] [--keep-wav]

Each step is fitted on renders of the current version at --seeds (the first seed is the scoring render, normally
0 = the default seed), applied, rendered and scored with likeness; a step that does not beat the running best is
dropped and the next step fits on the previous version. Steps (space-separated, applied in order):

  eq[:SCALE]       sectioneq.py on all sections (fitted on every --seeds render), one eq stage + lanes under the
                   first unused prefix (eq, rq, sq, tq, uq, vq), inserted right after the glue (after a glue the
                   limiter cannot fight its boosts), else before a clip, else appended
  ride             a contour ride pass: levelride.py (maps) / songride.py (songs) --contour --sections --win 0.5
                   --step 0.25 --amount 1.0 --slew 8 --accumulate, fitted on every --seeds render
  level[:MIN]      sectionlevel.py --lane <first unused slev, slev2..> --min MIN (default 0.5) on the scoring render
  width[:A,B]      widthfit.py --clip A,B (default 0.5,4; pass 2 is usually width:0.5,8) on the scoring render

Any step takes @S for its strength: width:0.5,8@0.5 (widthfit --strength), ride@0.5 / level@0.5 (--amount),
eq@0.5 (= eq:0.5). A final width:0.5,8 after the eq/ride steps refreshes the lanes they leave stale (chirper-two:
The Paradoxical Spiral +2.2, In Death - Is Life +1.0; Autonomy Lost only at @0.5).

The usual Catch Thirtythree order is "level width width:0.5,8 eq ride ride width:0.5,8" (level and width first when the master
is empty). A fitted master couples to the mix: after an instrument change, re-run the steps that depend on it.
Writes DIR/stepN-NAME.(yaml|json) for every step, DIR/best.* (+ DIR/best.yaml for maps, generated by tab2song)
and DIR/best.wav (every other render is deleted as soon as it is scored or fitted - temp audio is disposable;
--keep-wav keeps them); prints a table and, with --heldout, the held-out means of the input and of the best. Never edits
songs/ or tools/maps/: copy best.* there yourself (matching the original's JSON indent for maps) and commit.
"""
import json
import os
import shutil
import subprocess
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
PY = sys.executable


def opt(a, k, d):
    return type(d)(a[a.index(k) + 1]) if k in a else d


def run(cmd, **kw):
    return subprocess.run(cmd, capture_output=True, text=True, **kw)


class Stack:
    def __init__(self, song, ref, sections, out, seeds, chirp):
        self.ref, self.sections, self.out, self.seeds, self.chirp = ref, sections, out, seeds, chirp
        self.is_map = song.endswith(".json")
        self.ext = ".json" if self.is_map else ".yaml"
        self.secs = open(sections).read().split()

    def yaml_of(self, path):
        """The renderable song for a map or song path."""
        if not self.is_map:
            return path
        y = path[:-5] + ".yaml"
        if not os.path.exists(y):
            r = run([PY, os.path.join(HERE, "tab2song.py"), path, "-o", y])
            if r.returncode:
                sys.exit(f"tab2song failed on {path}: {r.stderr[-400:]}")
        return y

    def render(self, path, seeds):
        """Render path at each seed in parallel; returns {seed: wav}."""
        y, procs, wavs = self.yaml_of(path), [], {}
        for s in seeds:
            wav = f"{path.rsplit('.', 1)[0]}-s{s}.wav"
            wavs[s] = wav
            if not os.path.exists(wav):
                procs.append((s, subprocess.Popen(["nice", "-n", "15", self.chirp, "render", "-f", y, "--seed", str(s),
                                                   "-o", wav], stdout=subprocess.DEVNULL, stderr=subprocess.PIPE, text=True)))
        for s, p in procs:
            _, err = p.communicate()
            if p.returncode or not os.path.exists(wavs[s]):
                sys.exit(f"render failed ({path} seed {s}): {err[-400:]}")
        return wavs

    def score(self, wav):
        r = run(["nice", "-n", "15", PY, os.path.join(HERE, "likeness.py"), "sections", self.ref, wav, *self.secs])
        if r.returncode:
            sys.exit(f"likeness failed on {wav}: {r.stderr[-400:]}")
        d = json.loads(r.stdout)
        return d["total"], [round(s["total"], 1) for s in d["sections"]]

    def master(self, path):
        """(container, master dict) for a map or a one-line-JSON-master song."""
        if self.is_map:
            m = json.load(open(path))
            return m, m["head"].setdefault("master", {"fx": []})
        lines = open(path).read().splitlines(keepends=True)
        idx = [k for k, l in enumerate(lines) if l.startswith("master: ")]
        if not idx:
            return (lines, None), {"fx": []}
        return (lines, idx[0]), json.loads(lines[idx[0]][len("master: "):])

    def write_master(self, container, ms, dst):
        if self.is_map:
            json.dump(container, open(dst, "w"), indent=2, ensure_ascii=False)
            return
        lines, i = container
        line = "master: " + json.dumps(ms, ensure_ascii=False) + "\n"
        if i is None:
            t = [k for k, l in enumerate(lines) if l.startswith("tracks:")]
            lines.insert(t[0] if t else len(lines), line)
        else:
            lines[i] = line
        open(dst, "w").write("".join(lines))

    def free_lane(self, path, names):
        _, ms = self.master(path)
        used = set(ms.get("auto", {}))
        for n in names:
            if not any(u == n or u.startswith(n) and u[len(n):].isdigit() for u in used):
                return n
        sys.exit(f"no free lane name among {names}")

    # ---- steps: each returns (ok, message) after writing dst --------------------------------------------------
    def step_eq(self, cur, dst, arg, wavs, strength=None):
        prefix = self.free_lane(cur, ["eq", "rq", "sq", "tq", "uq", "vq"])
        r = run(["nice", "-n", "15", PY, os.path.join(HERE, "sectioneq.py"), self.ref, ",".join(wavs.values()),
                 self.sections, "--scale", strength or arg or "1.0", "--prefix", prefix])
        if r.returncode:
            return False, f"sectioneq failed: {r.stderr[-300:]}"
        s = json.loads(r.stdout)
        container, ms = self.master(cur)
        fx = ms.setdefault("fx", [])
        kind = lambda f: f.split()[0] if isinstance(f, str) else f.get("type")
        glue = [k for k, f in enumerate(fx) if kind(f) == "glue"]
        clip = [k for k, f in enumerate(fx) if kind(f) == "clip"]
        at = glue[0] + 1 if glue else clip[0] if clip else len(fx)
        fx.insert(at, s["eq"])
        ms.setdefault("auto", {}).update(s["auto"])
        self.write_master(container, ms, dst)
        return True, f"eq stage at {at} ({'after glue' if glue else 'before clip' if clip else 'appended'}), lanes {prefix}0-6"

    def step_ride(self, cur, dst, arg, wavs, strength=None):
        tool = "levelride.py" if self.is_map else "songride.py"
        common = ["--win", "0.5", "--step", "0.25", "--amount", strength or "1.0", "--contour", "--sections", self.sections,
                  "--slew", "8"]
        _, ms = self.master(cur)
        acc = ["--accumulate"] if (self.is_map or "fx" in ms and ms.get("fx")) else []
        r = run(["nice", "-n", "15", PY, os.path.join(HERE, tool), cur, self.ref, ",".join(wavs.values()), "-o", dst,
                 *common, *acc])
        if r.returncode or not os.path.exists(dst):
            return False, f"{tool} failed: {(r.stderr or r.stdout)[-300:]}"
        last = [l for l in (r.stdout + r.stderr).splitlines() if "ride" in l]
        return True, (last[-1][:90] if last else "ride")

    def step_level(self, cur, dst, arg, wavs, strength=None):
        used = set(self.master(cur)[1].get("auto", {}))
        lane = next(n for n in ["slev"] + [f"slev{k}" for k in range(2, 10)] if n not in used)
        r = run(["nice", "-n", "15", PY, os.path.join(HERE, "sectionlevel.py"), cur, wavs[self.seeds[0]], self.ref,
                 self.sections, "-o", dst, "--lane", lane, "--min", arg or "0.5", "--amount", strength or "1.0"])
        if r.returncode or not os.path.exists(dst):
            return False, f"sectionlevel: {(r.stdout + r.stderr).strip()[-200:]}"
        return True, (r.stdout + r.stderr).strip().splitlines()[-1][:90]

    def step_width(self, cur, dst, arg, wavs, strength=None):
        r = run(["nice", "-n", "15", PY, os.path.join(HERE, "widthfit.py"), cur, dst, wavs[self.seeds[0]], self.ref,
                 self.sections, "--clip", arg or "0.5,4", *(["--strength", strength] if strength else [])])
        if r.returncode or not os.path.exists(dst):
            return False, f"widthfit failed: {(r.stderr or r.stdout)[-300:]}"
        return True, (r.stdout + r.stderr).strip().splitlines()[-1][:90]


def drop_wavs(wavs, keep):
    """Delete renders that have served their purpose (the step is scored or the next one is fitted)."""
    if keep:
        return
    for w in set(wavs.values()):
        try:
            os.remove(w)
        except FileNotFoundError:
            pass


def heldout(chirp, song_yaml, ref, sections, seeds):
    r = run(["nice", "-n", "15", PY, os.path.join(HERE, "seedscore.py"), song_yaml, "--seeds", seeds, "--ref", ref,
             "--sections", sections], env={**os.environ, "CHIRP": chirp})
    try:
        d = json.loads(r.stdout.strip().splitlines()[-1])
        return d["mean"], d["per_seed"]
    except (ValueError, IndexError, KeyError):
        return None, r.stderr[-200:]


def main(a):
    if len(a) < 3 or "-h" in a or "--help" in a:
        sys.exit(__doc__)
    song, ref, sections = a[0], a[1], a[2]
    out = opt(a, "--out", "")
    if not out:
        sys.exit("--out DIR is required")
    steps = opt(a, "--steps", "eq ride ride").split()
    seeds = [int(s) for s in opt(a, "--seeds", "0,11").split(",")]
    chirp = opt(a, "--chirp", os.environ.get("CHIRP", "chirp"))
    min_gain = opt(a, "--min-gain", 0.0)
    keep_wav = "--keep-wav" in a
    os.makedirs(out, exist_ok=True)
    st = Stack(song, ref, sections, out, seeds, chirp)
    cur = os.path.join(out, "step0-base" + st.ext)
    shutil.copy(song, cur)
    wavs = st.render(cur, seeds)
    best, per = st.score(wavs[seeds[0]])
    base_score = best
    rows = [("base", best, per, "kept", "")]
    print(f"base {best} {per}", flush=True)
    for n, step in enumerate(steps, 1):
        base, _, strength = step.partition("@")
        name, _, arg = base.partition(":")
        fn = getattr(st, f"step_{name}", None)
        if fn is None:
            sys.exit(f"unknown step {name!r} (eq, ride, level, width)")
        dst = os.path.join(out, f"step{n}-{name}{st.ext}")
        ok, msg = fn(cur, dst, arg, wavs, strength or None)
        if not ok:
            rows.append((step, None, [], "failed", msg))
            print(f"{step}: FAILED {msg}", flush=True)
            continue
        new_wavs = st.render(dst, seeds[:1])
        sc, sp = st.score(new_wavs[seeds[0]])
        keep = sc > best + min_gain
        if not keep:
            drop_wavs(new_wavs, keep_wav)
        rows.append((step, sc, sp, "kept" if keep else "dropped", msg))
        print(f"{step}: {sc} {sp} {'KEPT' if keep else 'dropped'} - {msg}", flush=True)
        if keep:
            drop_wavs(wavs, keep_wav)
            cur, best = dst, sc
            wavs = st.render(dst, seeds)   # the remaining seeds, for the next fit
    shutil.copy(cur, os.path.join(out, "best" + st.ext))
    if st.is_map:
        shutil.copy(st.yaml_of(cur), os.path.join(out, "best.yaml"))
    shutil.copy(wavs[seeds[0]], os.path.join(out, "best.wav"))
    drop_wavs(wavs, keep_wav)
    print(f"\nmasterstack: {base_score} -> {best} ({best - base_score:+.3f}); best = {cur}")
    for step, sc, sp, verdict, msg in rows:
        print(f"  {step:12s} {sc if sc is not None else '-':>8} {verdict:8s} {sp}")
    if "--heldout" in a:
        hs = opt(a, "--heldout", "7,13")
        b = heldout(chirp, st.yaml_of(os.path.join(out, "step0-base" + st.ext)), ref, sections, hs)
        f = heldout(chirp, os.path.join(out, "best.yaml") if st.is_map else os.path.join(out, "best" + st.ext), ref,
                    sections, hs)
        print(f"held-out {hs}: base {b[0]} {b[1]}  best {f[0]} {f[1]}")


if __name__ == "__main__":
    main(sys.argv[1:])
